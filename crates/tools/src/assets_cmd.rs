//! `iwbtg assets index`: the global asset index keyed by content hash (#46).
//!
//! One games-repo folder holds one package per game (`<game-id>/game.toml`). The index lists every
//! media asset of every package once per distinct content, with every `(game, path)` that has it,
//! so equal assets in several games are one entry and print as `also in <game>`
//! (docs/content.md, Assets). The file is `<games dir>/assets-index.toml`, readable TOML and
//! deterministic: packages sort by folder name, files by package path.
//!
//! The key is the format's per-file content hash ([`iwbtg_format::content_hash_asset`]) over the
//! asset file alone: the package hash's domain separation and line-end rule, with no fabricated
//! package path (#1051). Media files are hashed as they are: the helper's fixed asset path has no
//! extension, so the text line-end normalization of the package hash does not apply.
//!
//! `tags` is the place for the AI tags the porting checklist fills later (#104). Rerunning the
//! command keeps the tags already in the file, so tagging is not lost. A duplicate group's first
//! place, in package order, stands in for the origin until the manifest carries release dates
//! (#1050).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use crate::trace_cmd::{ToolError, load_package};

/// The index file inside the games folder.
pub const INDEX_FILE: &str = "assets-index.toml";

/// Media file extensions that are assets (docs/format/assets.md): images and audio.
const ASSET_EXTENSIONS: [&str; 2] = ["png", "ogg"];

/// Lines above the TOML body. Not part of the data; `--check` compares them too.
const HEADER: &str = "\
# Generated by `iwbtg assets index`; rerun it to rebuild. `tags` are kept across runs.
# Format: docs/content.md (Assets). Command: docs/architecture/cli.md.
";

/// The whole index file.
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
struct AssetIndex {
    /// Index format version. 0 until docs/content.md (Assets) says otherwise.
    #[serde(default)]
    format: u32,
    /// One entry per distinct content, keyed by the lowercase hex content hash.
    #[serde(default)]
    assets: BTreeMap<String, IndexedAsset>,
}

/// One distinct asset content.
#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
struct IndexedAsset {
    /// Size of the file in bytes. The same hash has the same size.
    size: u64,
    /// AI tags, filled by the porting checklist (#104); empty until then.
    #[serde(default)]
    tags: Vec<String>,
    /// Every place the asset appears, in package then path order.
    found: Vec<Found>,
}

/// One `(game, path)` holding an asset.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
struct Found {
    /// The package folder name, which is the game id in the games repo.
    game: String,
    /// The package-relative path.
    path: String,
}

/// `iwbtg assets index <games dir> [--out <file>] [--check]`: writes the index and prints a
/// summary plus one `also in` line per duplicate group. With `check`, writes nothing and returns
/// `Ok(false)` (exit 1) when the file is missing or would change.
pub fn index_main(games: &Path, out: Option<&Path>, check: bool) -> Result<bool, ToolError> {
    if !games.is_dir() {
        return Err(ToolError::Message(format!(
            "{}: not a folder of game packages (one folder per game, each with game.toml)",
            games.display()
        )));
    }
    let out = out
        .map(Path::to_path_buf)
        .unwrap_or_else(|| games.join(INDEX_FILE));
    let existing = read_existing(&out)?;
    let index = build(games, existing.as_ref())?;
    let text = render(&index);

    println!(
        "indexed {} assets, {} unique, {} duplicate groups",
        index.assets.values().map(|a| a.found.len()).sum::<usize>(),
        index.assets.len(),
        index.assets.values().filter(|a| a.found.len() > 1).count()
    );
    for line in duplicate_lines(&index) {
        println!("{line}");
    }

    if check {
        return match std::fs::read_to_string(&out) {
            Ok(current) if current == text => {
                println!("up to date: {}", out.display());
                Ok(true)
            }
            Ok(_) => {
                println!("stale: {} (run `{}`)", out.display(), rerun_hint(games, &out));
                Ok(false)
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                println!("missing: {} (run `{}`)", out.display(), rerun_hint(games, &out));
                Ok(false)
            }
            Err(e) => Err(ToolError::Message(format!("{}: {e}", out.display()))),
        };
    }

    std::fs::write(&out, text.as_bytes())
        .map_err(|e| ToolError::Message(format!("{}: {e}", out.display())))?;
    Ok(true)
}

/// The command that rebuilds this index, for a `--check` message. `--out` is named only when the
/// index is not at the default place, so the suggested command writes the file that was checked.
fn rerun_hint(games: &Path, out: &Path) -> String {
    if out == games.join(INDEX_FILE) {
        format!("iwbtg assets index {}", games.display())
    } else {
        format!("iwbtg assets index {} --out {}", games.display(), out.display())
    }
}

/// Reads the index already at `path`, so its tags survive a rebuild. A broken file is an error,
/// not something to overwrite silently: it could be the only copy of hand-filled tags.
fn read_existing(path: &Path) -> Result<Option<AssetIndex>, ToolError> {
    match std::fs::read_to_string(path) {
        Ok(text) => toml::from_str(&text).map(Some).map_err(|e| {
            ToolError::Message(format!(
                "{}: not a valid asset index: {e} (delete it to rebuild without its tags)",
                path.display()
            ))
        }),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(ToolError::Message(format!("{}: {e}", path.display()))),
    }
}

/// Every package folder of the games repo, sorted by name. A folder counts when it has
/// `game.toml`; `_engines/` and anything else is skipped.
fn package_dirs(games: &Path) -> Result<Vec<(String, PathBuf)>, ToolError> {
    let io = |e: std::io::Error| ToolError::Message(format!("{}: {e}", games.display()));
    let mut dirs = Vec::new();
    for entry in std::fs::read_dir(games).map_err(io)? {
        let entry = entry.map_err(io)?;
        let path = entry.path();
        if !path.is_dir() || !path.join("game.toml").is_file() {
            continue;
        }
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| ToolError::Message(format!("{}: name is not UTF-8", path.display())))?;
        dirs.push((name, path));
    }
    dirs.sort_by(|a, b| a.0.cmp(&b.0));
    if dirs.is_empty() {
        return Err(ToolError::Message(format!(
            "no packages in {}: expected one folder per game, each with game.toml",
            games.display()
        )));
    }
    Ok(dirs)
}

/// Builds the index from every package, carrying the tags of `existing` over by hash.
fn build(games: &Path, existing: Option<&AssetIndex>) -> Result<AssetIndex, ToolError> {
    let mut index = AssetIndex {
        format: 0,
        assets: BTreeMap::new(),
    };
    for (game, dir) in package_dirs(games)? {
        // `load_package` bundles the package's engine pack from `../_engines/<pack>/`, so shared
        // kid sprites and sounds are indexed too.
        let files = load_package(&dir)?;
        for (path, bytes) in files.iter() {
            if path.starts_with(iwbtg_format::files::TESTS_DIR) || !is_asset(path) {
                continue;
            }
            let hash = asset_hash(bytes);
            let asset = index.assets.entry(hash).or_insert_with(|| IndexedAsset {
                size: bytes.len() as u64,
                tags: Vec::new(),
                found: Vec::new(),
            });
            asset.found.push(Found {
                game: game.clone(),
                path: path.to_owned(),
            });
        }
    }
    if let Some(existing) = existing {
        for (hash, asset) in &mut index.assets {
            if let Some(old) = existing.assets.get(hash) {
                asset.tags.clone_from(&old.tags);
            }
        }
    }
    Ok(index)
}

/// True when `path` is a media asset: a `.png` or `.ogg` file. Everything else (`.toml` sidecars,
/// `game.toml`, Markdown) is data.
fn is_asset(path: &str) -> bool {
    path.rsplit_once('.')
        .is_some_and(|(_, ext)| ASSET_EXTENSIONS.iter().any(|a| ext.eq_ignore_ascii_case(a)))
}

/// The content-hash key of one asset file, lowercase hex.
fn asset_hash(bytes: &[u8]) -> String {
    hex(&iwbtg_format::content_hash_asset(bytes))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// The index as file text: the header, then the TOML body.
fn render(index: &AssetIndex) -> String {
    let body = toml::to_string_pretty(index).expect("the index is plain data");
    format!("{HEADER}{body}")
}

/// One line per duplicate group: the first place in package order, then every other place as
/// `also in`. A place with the same path as the first prints as the game alone.
fn duplicate_lines(index: &AssetIndex) -> Vec<String> {
    let mut lines = Vec::new();
    for asset in index.assets.values().filter(|a| a.found.len() > 1) {
        let first = &asset.found[0];
        let others: Vec<String> = asset.found[1..]
            .iter()
            .map(|f| {
                if f.path == first.path {
                    f.game.clone()
                } else {
                    format!("{}/{}", f.game, f.path)
                }
            })
            .collect();
        lines.push(format!(
            "duplicate: {}/{} also in {}",
            first.game,
            first.path,
            others.join(", ")
        ));
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_png_and_ogg_are_assets() {
        for asset in ["sprites/kid.png", "sounds/jump.ogg", "engine/a1/art/logo.PNG"] {
            assert!(is_asset(asset), "{asset}");
        }
        for data in ["game.toml", "sprites/kid.toml", "CREDITS.md", "music/x.wav"] {
            assert!(!is_asset(data), "{data}");
        }
    }

    #[test]
    fn the_hash_depends_only_on_the_bytes() {
        assert_eq!(asset_hash(b"same"), asset_hash(b"same"));
        assert_ne!(asset_hash(b"same"), asset_hash(b"other"));
        // The placeholder path has no text extension, so CRLF is hashed as it is.
        assert_ne!(asset_hash(b"a\r\nb"), asset_hash(b"a\nb"));
    }

    #[test]
    fn the_check_hint_names_out_only_when_it_is_custom() {
        let games = Path::new("games");
        assert_eq!(
            rerun_hint(games, &games.join(INDEX_FILE)),
            "iwbtg assets index games"
        );
        assert_eq!(
            rerun_hint(games, Path::new("elsewhere.toml")),
            "iwbtg assets index games --out elsewhere.toml"
        );
    }

    #[test]
    fn duplicates_print_with_also_in() {
        let mut assets = BTreeMap::new();
        assets.insert(
            "00".to_owned(),
            IndexedAsset {
                size: 4,
                tags: Vec::new(),
                found: vec![
                    Found {
                        game: "alpha".to_owned(),
                        path: "sprites/kid.png".to_owned(),
                    },
                    Found {
                        game: "beta".to_owned(),
                        path: "sprites/kid.png".to_owned(),
                    },
                    Found {
                        game: "gamma".to_owned(),
                        path: "art/kid.png".to_owned(),
                    },
                ],
            },
        );
        assets.insert(
            "01".to_owned(),
            IndexedAsset {
                size: 1,
                tags: Vec::new(),
                found: vec![Found {
                    game: "alpha".to_owned(),
                    path: "sounds/only.ogg".to_owned(),
                }],
            },
        );
        let index = AssetIndex { format: 0, assets };
        assert_eq!(
            duplicate_lines(&index),
            vec!["duplicate: alpha/sprites/kid.png also in beta, gamma/art/kid.png"]
        );
    }
}
